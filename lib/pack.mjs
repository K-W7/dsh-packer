/**
 * 构建 manifest.json 内容。
 *
 * v0.7.0：新增可选字段 `mode`（源文件权限位）—— 旧实现打包时一律写 0644、
 * 恢复时也不还原，导致 skills 里的可执行脚本恢复后失去 +x。旧包没有该字段则跳过还原。
 */
export function buildManifest({ modules, mode, note, files, sanitized = false, redactions = 0 }) {
  return {
    schemaVersion: SCHEMA_VERSION,
    tool: TOOL_NAME,
    createdAt: new Date().toISOString(),
    mode,
    note: note || '',
    modules,
    sanitized: sanitized === true,
    redactions: Number(redactions) || 0,
    files: files.map((f) => {
      const entry = { module: f.module, rel: f.rel, size: Number(f.size) || 0, sha256: f.sha256 }
      if (Number.isInteger(f.mode) && f.mode > 0) entry.mode = f.mode & 0o777
      return entry
    }),
  }
}

/** 对外 manifest：去掉内部字段（_dir）与逐文件数组（详情用 files 单独返回） */
export function publicManifest(manifest) {
  return {
    schemaVersion: manifest.schemaVersion,
    mode: manifest.mode,
    modules: Array.isArray(manifest.modules) ? manifest.modules : [],
    note: manifest.note || '',
    createdAt: manifest.createdAt,
    sanitized: manifest.sanitized === true,
    redactions: Number(manifest.redactions) || 0,
  }
}

