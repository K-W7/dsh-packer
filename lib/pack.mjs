// ---------- staging ----------

/**
 * 递归收集 staging 目录里的文件，返回 { name（'/' 分隔）, data, unixMode }[]。
 * @param {Map<string, number>} [modeMap] rel（module/rel）→ 源文件权限位
 */
async function collectStageEntries(root, rel = '', modeMap = null) {
  const out = []
  const entries = await fsp.readdir(path.join(root, rel), { withFileTypes: true })
  for (const e of entries) {
    const childRel = rel ? `${rel}/${e.name}` : e.name
    if (e.isDirectory()) {
      out.push(...(await collectStageEntries(root, childRel, modeMap)))
    } else if (e.isFile()) {
      out.push({
        name: childRel,
        data: await fsp.readFile(path.join(root, childRel)),
        unixMode: modeMap?.get(childRel) ?? undefined,
      })
    }
  }
  return out
}

